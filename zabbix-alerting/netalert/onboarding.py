"""Discovery-assisted onboarding: suggestions -> operator decisions -> both production inventories.

The two inventories stay the source of truth for what is monitored. This module only
  * proposes candidates from a read-only discovery snapshot (never approves anything by itself),
  * records operator decisions in config/onboarding.<env>.yaml (exclusions, role/severity/description
    choices, operator-confirmed pairings, and the identity of every approved port),
  * regenerates config/interfaces.<env>.yaml and config/network-health.<env>.yaml deterministically,
    keeping every existing entry exactly as it is unless the operator explicitly changed or removed it,
  * gates deployment (verify): fail closed on anything unresolved, stale, unsupported or unreviewed.
"""
