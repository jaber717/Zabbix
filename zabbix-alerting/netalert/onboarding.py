"""Discovery-assisted onboarding: suggestions -> operator decisions -> both production inventories.

The two inventories stay the source of truth for what is monitored. This module only
  * proposes candidates from a read-only discovery snapshot (never approves anything by itself),
  * records operator decisions in config/onboarding.<env>.yaml (exclusions, role/severity/description
    choices, operator-confirmed pairings, and the identity of every approved port),
  * regenerates config/interfaces.<env>.yaml and config/network-health.<env>.yaml deterministically,
    keeping every existing entry exactly as it is unless the operator explicitly changed or removed it,
  * gates deployment (verify): fail closed on anything unresolved, stale, unsupported or unreviewed.
"""
import copy
import hashlib
import os
import re
import time

import yaml

from . import config as icfg
from . import handover, planner

DECISIONS_VERSION = 1
ROLES = ("ISP", "WAN", "DCI", "P2P")
HEALTH_FEATURES = ("device_unreachable", "snmp_stale", "cpu", "memory", "ospf", "bgp")
SNMP_FEATURES = ("snmp_stale", "cpu", "memory", "ospf", "bgp")
DEFAULT_RULES = {
    "exclude_ports": r"(?i)^(lo|loopback|null|nu|vlan|vl|tunnel|tu|mgmt|management|ma|bdi|nve|dialer|virtual-|"
                     r"inband|vif|sup-eth|cpu|stackport|ap)\d*",
    "roles": {
        "ISP": r"(?i)(\bisp\b|internet|transit|upstream)",
        "DCI": r"(?i)(\bdci\b|inter[- ]?dc\b|data ?cent(er|re) interconnect)",
        "WAN": r"(?i)(\bwan\b|\bmpls\b|l2vpn|\bvpls\b|\bmetro\b)",
        "P2P": r"(?i)(\bp2p\b|\bptp\b|point[- ]to[- ]point)",
    },
    "isp_names": [],
    "severity": {"ISP": "high", "WAN": "high", "DCI": "high", "P2P": "high"},
    "interface_policy": {"utilization": {"enabled": True, "threshold": 70, "recovery": 65}},
    "health_severity": {"device_unreachable": "high", "snmp_stale": "high", "cpu": "high", "memory": "high",
                        "ospf": "high", "bgp": "high"},
    "health_suggest": ["device_unreachable", "snmp_stale"],
    "stale_after": "15m",
    "site_tag": "site",
}
IFACE_HEADER = ("# PRODUCTION-STYLE interface inventory GENERATED by ./onboard.sh from approved, live-verified\n"
                "# discovery. Change it through ./onboard.sh; a hand edit is detected by --verify and must be\n"
                "# re-reviewed before deployment. Existing entries are preserved verbatim.\n")
HEALTH_HEADER = ("# Network Health inventory GENERATED by ./onboard.sh from approved devices/features only.\n"
                 "# Network Health is v1.0.3 and UNTESTED on a real Zabbix (see docs/NETWORK-HEALTH.md).\n")


class OnboardError(Exception):
    pass


# ----------------------------------------------------------------------------------------------- files

def load_rules(base):
    rules = copy.deepcopy(DEFAULT_RULES)
    path = os.path.join(base, "config", "onboarding-rules.yaml")
    if os.path.isfile(path):
        raw = icfg.load_file(path)
        unknown = sorted(set(raw) - set(DEFAULT_RULES))
        if unknown:
            raise OnboardError("%s: unknown key(s) %s" % (path, ", ".join(unknown)))
        for k, v in raw.items():
            rules[k] = dict(rules[k], **v) if isinstance(rules[k], dict) and isinstance(v, dict) else v
    for role in rules["roles"]:
        if role not in ROLES:
            raise OnboardError("onboarding rules: unknown role %s (use %s)" % (role, ", ".join(ROLES)))
    for role, sev in rules["severity"].items():
        if sev not in icfg.SEVERITIES:
            raise OnboardError("onboarding rules: severity %s for %s is invalid" % (sev, role))
    try:
        rules["_stale_s"] = icfg.parse_interval(rules["stale_after"])
        rules["_rx"] = dict((r, re.compile(p)) for r, p in rules["roles"].items())
        rules["_exclude"] = re.compile(rules["exclude_ports"])
    except (re.error, ValueError) as exc:
        raise OnboardError("onboarding rules: %s" % exc)
    return rules


def paths(base, env_name):
    c = os.path.join(base, "config")
    return {"interfaces": os.path.join(c, "interfaces.%s.yaml" % env_name),
            "health": os.path.join(c, "network-health.%s.yaml" % env_name),
            "decisions": os.path.join(c, "onboarding.%s.yaml" % env_name),
            "state": os.path.join(base, "state", "onboarding", env_name)}


def read_yaml(path):
    if not os.path.isfile(path):
        return {}
    data = icfg.load_file(path)
    if not isinstance(data, dict):
        raise OnboardError("%s: top level must be a mapping" % path)
    return data


def file_sha(path):
    if not os.path.isfile(path):
        return ""
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


def load_decisions(path):
    d = read_yaml(path)
    if d and d.get("version") != DECISIONS_VERSION:
        raise OnboardError("%s: unsupported version %r" % (path, d.get("version")))
    return {"version": DECISIONS_VERSION, "written": dict(d.get("written") or {}),
            "ports": dict(d.get("ports") or {}), "devices": dict(d.get("devices") or {})}


def atomic_write(path, text, backup_dir=None):
    if backup_dir and os.path.isfile(path):
        os.makedirs(backup_dir, exist_ok=True)
        stamp = time.strftime("%Y%m%dT%H%M%S")
        with open(path, "rb") as src, open(os.path.join(backup_dir, "%s.%s" % (os.path.basename(path), stamp)), "wb") as dst:
            dst.write(src.read())
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, path)


def save_decisions(path, dec):
    text = ("# Onboarding decisions written by ./onboard.sh (approved entries themselves live in the inventories).\n"
            + yaml.safe_dump(dec, default_flow_style=False, sort_keys=True, allow_unicode=True, width=1000))
    atomic_write(path, text)


def pid(host, port):
    return "%s|%s" % (host, port)


# ----------------------------------------------------------------------------------------------- model

class Row(object):
    """One network port (kind='port') or one device (kind='device') as the reviewer sees it."""

    def __init__(self, **kw):
        self.__dict__.update(kw)


def _named_hosts(text, other_hosts):
    """Zabbix hosts whose exact name appears as a whole token in a description (a hint, never proof)."""
    return [h for h in other_hosts
            if len(h) >= 3 and re.search(r"(?i)(^|[^a-z0-9_.-])%s([^a-z0-9_.-]|$)" % re.escape(h), text or "")]


def _suggest_role(alias, rules, other_hosts):
    """(role, reason, peer_hint). Only a suggestion: nothing is approved from it."""
    text = alias or ""
    named = _named_hosts(text, other_hosts)
    hint = named[0] if len(named) == 1 else None
    for role in ("ISP", "DCI", "WAN", "P2P"):
        rx = rules["_rx"].get(role)
        if rx and rx.search(text):
            return role, "description matches %s pattern" % role, hint
    for name in rules.get("isp_names") or []:
        if name and re.search(r"(?i)\b%s\b" % re.escape(name), text):
            return "ISP", "description names provider '%s'" % name, hint
    if hint:
        return "P2P", "description names Zabbix host '%s'" % hint, hint
    return None, "", None


def build(snap, rules, iface_raw, health_raw, dec, now=None):
    """Return {'ports': [Row], 'devices': [Row], 'by_id': {}, 'findings': []} (pure, no I/O)."""
    now = int(now if now is not None else time.time())
    hosts = snap["hosts"]
    yaml_hosts = iface_raw.get("hosts") or {}
    in_yaml = set()
    for h, hraw in yaml_hosts.items():
        for p in ((hraw or {}).get("interfaces") or {}):
            in_yaml.add(pid(str(h), str(p)))
    rows, by_id = [], {}
    names = sorted(hosts)

    def add(host, port, p):
        rid = pid(host, port)
        d = dec["ports"].get(rid) or {}
        h = hosts.get(host)
        others = [n for n in names if n != host]
        alias = (p or {}).get("alias", "")
        role, why, hint = _suggest_role(alias, rules, others) if p else (None, "", None)
        excluded_by_name = bool(rules["_exclude"].match(port))
        yraw = ((yaml_hosts.get(host) or {}).get("interfaces") or {}).get(port) if rid in in_yaml else None
        blockers, review = [], []
        if h is None:
            blockers.append("host not found in Zabbix")
        elif not h["enabled"]:
            blockers.append("host disabled in Zabbix")
        elif not h["snmp"]["present"]:
            blockers.append("host has no SNMP interface")
        if h is not None and p is None:
            blockers.append("port no longer discovered on host")
        if '"' in port or "\\" in port:
            blockers.append("interface name contains a quote or backslash: Zabbix cannot use it as a macro context")
        if p is not None:
            if p["dup"]:
                blockers.append("ambiguous: more than one interface item set uses this name")
            if p["fresh"] != "fresh":
                blockers.append("status item %s%s" % (p["fresh"], (": %s" % p["items"]["status"]["error"])
                                                      if p["fresh"] == "unsupported" else ""))
            if d.get("index") and p.get("index") and str(d["index"]) != str(p["index"]):
                review.append("SNMP index changed %s -> %s since approval (re-approve after checking the port)"
                              % (d["index"], p["index"]))
        decision = d.get("decision")
        if rid in in_yaml:
            status = "REMOVE" if decision == "excluded" else "APPROVED"
        else:
            status = {"approved": "APPROVED", "excluded": "EXCLUDED"}.get(decision, "PENDING")
        eff_role = d.get("role") or (yraw or {}).get("role") or role
        eff_sev = d.get("severity") or (yraw or {}).get("severity") or rules["severity"].get(eff_role or "", "high")
        descr = d.get("description") or (yraw or {}).get("description") or alias or (
            "%s %s (no ifAlias on device)" % (eff_role or "port", port))
        candidate = bool(rid in in_yaml or decision or (role and not excluded_by_name))
        r = Row(kind="port", id=rid, host=host, port=port, alias=alias, p=p, h=h, suggest_role=role,
                role_reason=why, peer_hint=hint, role=eff_role, severity=eff_sev, description=descr,
                status=status, in_yaml=rid in in_yaml, yaml=yraw, decision=d, blockers=blockers, review=review,
                candidate=candidate, pair=d.get("pair"), pair_source=d.get("pair_source", ""), pair_hints=[],
                link_id=(yraw or {}).get("link_id", ""), excluded_by_name=excluded_by_name)
        rows.append(r)
        by_id[rid] = r

    for host in names:
        for port in sorted(hosts[host]["ports"]):
            add(host, port, hosts[host]["ports"][port])
    for rid in sorted(in_yaml | set(dec["ports"])):
        if rid not in by_id:
            host, port = rid.split("|", 1)
            if host in hosts or rid in in_yaml or dec["ports"][rid].get("decision") == "approved":
                add(host, port, None)

    _pairing(rows, by_id, snap)
    for r in rows:
        if r.status == "APPROVED" and r.role == "P2P" and not (r.pair or r.link_id):
            r.review.append("P2P port has no verified or operator-confirmed peer (link_id left empty)")

    devices = _devices(snap, rules, health_raw, dec, rows)
    return {"ports": rows, "devices": devices, "by_id": by_id, "now": now}


def _pairing(rows, by_id, snap):
    """Verified pairs come only from NetBox cables or explicit operator confirmation. Description
    cross-references are shown as hints and never become a link_id on their own."""
    for r in rows:
        nb = (r.p or {}).get("netbox_peer")
        if nb and not r.pair:
            other = by_id.get(pid(nb[0], nb[1]))
            back = (other.p or {}).get("netbox_peer") if other else None
            if other and back == [r.host, r.port]:
                r.pair, r.pair_source = other.id, "netbox-cable"
    cands = [r for r in rows if r.candidate and r.peer_hint]
    for r in cands:
        mutual = [o for o in cands if o.host == r.peer_hint and o.peer_hint == r.host]
        if len(mutual) == 1:
            r.pair_hints = [mutual[0].id]
        elif len(mutual) > 1:
            r.review.append("ambiguous peer: %d ports on %s describe this host" % (len(mutual), r.peer_hint))
    for r in rows:
        if r.pair and r.pair in by_id:
            o = by_id[r.pair]
            if o.pair not in (None, r.id) and o.pair_source:
                r.review.append("pairing conflict: %s is paired with %s" % (o.id, o.pair))


def _devices(snap, rules, health_raw, dec, port_rows):
    ydev = health_raw.get("devices") or {}
    approved_hosts = set(r.host for r in port_rows if r.status == "APPROVED")
    out = []
    for host in sorted(set(snap["hosts"]) | set(str(k) for k in ydev) | set(dec["devices"])):
        h = snap["hosts"].get(host)
        d = dec["devices"].get(host) or {}
        yraw = ydev.get(host)
        plat = d.get("platform") or (yraw or {}).get("platform") or (h or {}).get("platform")
        support, unsupported = {}, {}
        for f in HEALTH_FEATURES:
            if h is None:
                unsupported[f] = "host not in Zabbix"
            elif f in SNMP_FEATURES and not h["snmp"]["present"]:
                unsupported[f] = "no SNMP interface"
            elif f in ("cpu", "memory") and not plat:
                unsupported[f] = "platform unknown (set it: no CPU/memory template is guessed)"
            elif f in ("ospf", "bgp"):
                ev = [i for i in h["health_items"].get(f, []) if i["state"] == "0" and i["lastclock"]]
                support[f] = ("existing %s items return data" % f.upper()) if ev else \
                    "UNVERIFIED: confirm the device answers the %s MIB (snmpwalk) before enabling" % f.upper()
            else:
                support[f] = "ok"
        suggested = [f for f in rules["health_suggest"] if f in support] if host in approved_hosts else []
        if yraw is not None:
            feats = [f for f in HEALTH_FEATURES if f in yraw and yraw[f] is not False]
        else:
            feats = list(d.get("features") or suggested)
        decision = d.get("decision")
        if yraw is not None:
            status = "REMOVE" if decision == "excluded" else "APPROVED"
        else:
            status = {"approved": "APPROVED", "excluded": "EXCLUDED"}.get(decision, "PENDING")
        if d.get("features") is not None:
            feats = list(d["features"])
        blockers = []
        if h is None:
            blockers.append("host not found in Zabbix")
        elif not h["enabled"]:
            blockers.append("host disabled in Zabbix")
        for f in feats:
            if f in unsupported:
                blockers.append("%s unsupported: %s" % (f, unsupported[f]))
        out.append(Row(kind="device", id=host, host=host, h=h, platform=plat, features=feats, suggested=suggested,
                       support=support, unsupported=unsupported, status=status, yaml=yraw, decision=d,
                       blockers=blockers, review=[], candidate=bool(suggested or yraw is not None or decision),
                       in_yaml=yraw is not None))
    return out


# ------------------------------------------------------------------------------------------ decisions

def fingerprint(row):
    st = (row.p or {}).get("items", {}).get("status") if row.p else None
    return {"hostid": (row.h or {}).get("hostid", ""), "itemid": st["itemid"] if st else "",
            "index": (row.p or {}).get("index") or ""}


def decide_port(dec, row, decision, now):
    d = dict(dec["ports"].get(row.id) or {})
    d["decision"] = decision
    d["decided_at"] = int(now)
    if decision == "approved":
        d.update(fingerprint(row))
        d.setdefault("role", row.role)
        d.setdefault("severity", row.severity)
    dec["ports"][row.id] = d


def set_pair(dec, a, b, source):
    for x, y in ((a, b), (b, a)):
        d = dict(dec["ports"].get(x.id) or {})
        d["pair"], d["pair_source"] = (y.id, source) if y else (None, "")
        dec["ports"][x.id] = d


# ------------------------------------------------------------------------------------------ generation

def link_id_for(a, b):
    ends = sorted(re.sub(r"[^a-z0-9]+", "-", ("%s-%s" % (x.host, x.port)).lower()).strip("-") for x in (a, b))
    return "--".join(ends)


def _site(h, rules):
    if not h:
        return ""
    vals = [v for k, v in h["tags"] if k == rules["site_tag"] and v]
    if len(vals) == 1:
        return vals[0]
    return (h.get("netbox") or {}).get("site", "")


def generate_interfaces(model, iface_raw, rules):
    out = {"hosts": {}}
    if "defaults" in iface_raw:
        out["defaults"] = copy.deepcopy(iface_raw["defaults"])
    by_id = model["by_id"]
    approved = [r for r in model["ports"] if r.status == "APPROVED"]
    for r in approved:
        hraw = (iface_raw.get("hosts") or {}).get(r.host) or {}
        if r.host not in out["hosts"]:
            host_entry = dict((k, copy.deepcopy(v)) for k, v in hraw.items() if k != "interfaces")
            if "site" not in host_entry:
                host_entry["site"] = _site(r.h, rules)
            host_entry["interfaces"] = {}
            out["hosts"][r.host] = host_entry
        if r.yaml is not None:
            entry = copy.deepcopy(r.yaml)
            for f in ("role", "severity", "description"):
                if r.decision.get(f) and r.decision[f] != entry.get(f):
                    entry[f] = r.decision[f]
        else:
            entry = {"description": r.description, "role": r.role or "", "severity": r.severity,
                     "utilization": copy.deepcopy(rules["interface_policy"]["utilization"])}
        peer = by_id.get(r.pair) if r.pair else None
        if peer is not None and peer.status == "APPROVED" and not entry.get("link_id"):
            entry["link_id"] = (peer.yaml or {}).get("link_id") or link_id_for(r, peer)
        if not entry.get("role"):
            entry.pop("role", None)
        out["hosts"][r.host]["interfaces"][r.port] = entry
    return out


def generate_health(model, health_raw, rules):
    out = {"devices": {}}
    if "defaults" in health_raw:
        out["defaults"] = copy.deepcopy(health_raw["defaults"])
    for r in model["devices"]:
        if r.status != "APPROVED" or not r.features:
            continue
        entry = copy.deepcopy(r.yaml) if r.yaml is not None else {"site": _site(r.h, rules)}
        for f in HEALTH_FEATURES:
            if f in r.features and f not in entry:
                entry[f] = {"severity": rules["health_severity"].get(f, "high")}
            elif f not in r.features:
                entry.pop(f, None)
        if r.platform and ("cpu" in r.features or "memory" in r.features):
            entry["platform"] = r.platform
        out["devices"][r.host] = entry
    return out


def render(header, data):
    return header + yaml.safe_dump(data, default_flow_style=False, sort_keys=True, allow_unicode=True, width=1000)


def validate_generated(iface_doc, health_doc):
    from nethealth import config as hcfg
    probs = ["interfaces: %s: %s" % (p.label(), p.message) for p in icfg.parse(iface_doc).problems]
    probs += ["network-health: %s/%s: %s" % x for x in hcfg.parse(health_doc).problems]
    return probs


def write_all(base, env_name, model, rules, dec, iface_raw, health_raw):
    """Generate, validate, write both inventories + decisions. Returns (paths, problems). Writes nothing
    when the generated documents do not pass the projects' own strict validation."""
    p = paths(base, env_name)
    idoc, hdoc = generate_interfaces(model, iface_raw, rules), generate_health(model, health_raw, rules)
    probs = validate_generated(idoc, hdoc)
    if probs:
        return p, probs
    bdir = os.path.join(p["state"], "backups")
    for key, header, doc in (("interfaces", IFACE_HEADER, idoc), ("health", HEALTH_HEADER, hdoc)):
        text = render(header, doc)
        old = open(p[key], encoding="utf-8").read() if os.path.isfile(p[key]) else None
        if text != old:
            atomic_write(p[key], text, bdir)
    for r in model["ports"]:                         # entries removed on request lose their decision record
        if r.status == "REMOVE":
            dec["ports"][r.id]["decision"] = "excluded"
        if r.status == "APPROVED" and not dec["ports"].get(r.id, {}).get("itemid") and r.p:
            d = dict(dec["ports"].get(r.id) or {}, decision="approved")
            d.update(fingerprint(r))
            dec["ports"][r.id] = d
    for r in model["devices"]:
        if r.status == "APPROVED" and r.features:
            dec["devices"][r.host] = dict(dec["devices"].get(r.host) or {}, decision="approved",
                                          features=list(r.features), platform=r.platform)
    dec["written"] = {"interfaces_sha256": file_sha(p["interfaces"]), "health_sha256": file_sha(p["health"])}
    save_decisions(p["decisions"], dec)
    return p, []


# ------------------------------------------------------------------------------------------ deploy gate

def verify(client, base, env_name, model, dec, iface_raw, health_raw):
    """(failures, warnings). Any failure = do not deploy. Uses a fresh discovery (model) and read-only API."""
    p = paths(base, env_name)
    fails, warns = [], []
    if not dec["written"]:
        fails.append("inventories were never written by ./onboard.sh for this environment - review and write first")
    else:
        for key, fk in (("interfaces", "interfaces_sha256"), ("health", "health_sha256")):
            if file_sha(p[key]) != dec["written"].get(fk, ""):
                fails.append("%s changed since the last reviewed write (hand edit or other tool) - re-run "
                             "./onboard.sh and write (w) to re-review it" % os.path.relpath(p[key], base))
    probs = validate_generated(iface_raw or {"hosts": {}}, health_raw or {"devices": {}})
    fails += probs
    extras = {}
    for r in model["ports"]:
        if r.status in ("APPROVED", "REMOVE"):
            for b in r.blockers:
                fails.append("%s / %s: %s" % (r.host, r.port, b))
            for w in r.review:
                (fails if "index changed" in w else warns).append("%s / %s: %s" % (r.host, r.port, w))
            d = dec["ports"].get(r.id) or {}
            if r.status == "APPROVED" and d.get("itemid") and r.h is not None:
                extras[(r.host, r.port)] = {"hostid": str(d.get("hostid", "")), "itemid": str(d["itemid"]),
                                            "index": str(d.get("index", "")), "ifname": r.port}
            elif r.status == "APPROVED" and r.p is not None:
                fails.append("%s / %s: no recorded identity (approve it in ./onboard.sh)" % (r.host, r.port))
    if extras:
        live = planner.get_hosts(client, sorted(set(h for h, _ in extras)))
        for (host, port), why in sorted(handover.cross_check(client, extras, live).items()):
            fails.append("%s / %s: identity drift since approval: %s" % (host, port, why))
    for r in model["devices"]:
        if r.status == "APPROVED":
            for b in r.blockers:
                fails.append("%s (network health): %s" % (r.host, b))
            for f in r.features:
                if "UNVERIFIED" in r.support.get(f, ""):
                    warns.append("%s (network health): %s enabled although %s" % (r.host, f, r.support[f]))
    pending = [r for r in model["ports"] if r.status == "PENDING" and r.candidate]
    if pending:
        warns.append("%d suggested candidate port(s) are still PENDING review (not monitored by this project)" % len(pending))
    return sorted(set(fails)), sorted(set(warns))
